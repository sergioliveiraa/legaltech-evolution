DROP TABLE IF EXISTS certificacao CASCADE;
DROP TABLE IF EXISTS pesquisa_nps CASCADE;
DROP TABLE IF EXISTS atendimento CASCADE;
DROP TABLE IF EXISTS execucao_automacao CASCADE;
DROP TABLE IF EXISTS evento_documento CASCADE;
DROP TABLE IF EXISTS documento CASCADE;
DROP TABLE IF EXISTS acordo CASCADE;
DROP TABLE IF EXISTS movimentacao_processo CASCADE;
DROP TABLE IF EXISTS processo_juridico CASCADE;
DROP TABLE IF EXISTS pagamento CASCADE;
DROP TABLE IF EXISTS historico_status_contrato CASCADE;
DROP TABLE IF EXISTS contrato CASCADE;
DROP TABLE IF EXISTS plano CASCADE;
DROP TABLE IF EXISTS score_preditivo CASCADE;
DROP TABLE IF EXISTS modelo_preditivo CASCADE;
DROP TABLE IF EXISTS fechamento_financeiro CASCADE;
DROP TABLE IF EXISTS vinculo CASCADE;
DROP TABLE IF EXISTS cliente CASCADE;
DROP TABLE IF EXISTS legaltech CASCADE;
DROP TABLE IF EXISTS localidade CASCADE;

CREATE TABLE localidade (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            cidade VARCHAR(100) NOT NULL,
                            uf VARCHAR(2) NOT NULL,
                            regiao VARCHAR(20) NOT NULL,
                            latitude DOUBLE PRECISION NOT NULL,
                            longitude DOUBLE PRECISION NOT NULL,
                            CONSTRAINT uk_localidade UNIQUE (cidade, uf)
);

CREATE TABLE legaltech (
                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           nome_legaltech VARCHAR(100) NOT NULL,
                           segmento VARCHAR(50) NOT NULL,
                           porte VARCHAR(30) NOT NULL,
                           ano_fundacao INT NOT NULL,
                           modelo_negocio VARCHAR(50) NOT NULL,
                           investimento_estimado NUMERIC(15, 2) NOT NULL,
                           localidade_id BIGINT NOT NULL,
                           CONSTRAINT fk_legaltech_localidade FOREIGN KEY (localidade_id) REFERENCES localidade(id)
);

CREATE TABLE certificacao (
                              id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              legaltech_id BIGINT NOT NULL,
                              tipo_certificacao VARCHAR(50) NOT NULL,
                              situacao VARCHAR(30) NOT NULL,
                              data_situacao DATE NOT NULL,
                              CONSTRAINT fk_certificacao_legaltech FOREIGN KEY (legaltech_id) REFERENCES legaltech(id)
);

CREATE TABLE cliente (
                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         tipo_cliente VARCHAR(20) NOT NULL,
                         porte_cliente VARCHAR(30) NOT NULL,
                         area_juridica_principal VARCHAR(50) NOT NULL,
                         canal_aquisicao VARCHAR(50) NOT NULL,
                         data_cadastro DATE NOT NULL,
                         localidade_id BIGINT NOT NULL,
                         CONSTRAINT fk_cliente_localidade FOREIGN KEY (localidade_id) REFERENCES localidade(id)
);

CREATE TABLE vinculo (
                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         cliente_id BIGINT NOT NULL,
                         legaltech_id BIGINT NOT NULL,
                         data_inicio DATE NOT NULL,
                         data_fim DATE,
                         status_vinculo VARCHAR(20) NOT NULL,
                         CONSTRAINT fk_vinculo_cliente FOREIGN KEY (cliente_id) REFERENCES cliente(id),
                         CONSTRAINT fk_vinculo_legaltech FOREIGN KEY (legaltech_id) REFERENCES legaltech(id),
                         CONSTRAINT uk_cliente_legaltech UNIQUE (cliente_id, legaltech_id, data_inicio)
);

CREATE TABLE plano (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       nome_plano VARCHAR(50) NOT NULL UNIQUE,
                       valor_referencia NUMERIC(12, 2) NOT NULL
);

CREATE TABLE contrato (
                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          vinculo_id BIGINT NOT NULL,
                          plano_id BIGINT NOT NULL,
                          data_inicio DATE NOT NULL,
                          data_fim DATE,
                          valor_mensal NUMERIC(12, 2) NOT NULL,
                          data_cancelamento DATE,
                          CONSTRAINT fk_contrato_vinculo FOREIGN KEY (vinculo_id) REFERENCES vinculo(id),
                          CONSTRAINT fk_contrato_plano FOREIGN KEY (plano_id) REFERENCES plano(id)
);

CREATE TABLE historico_status_contrato (
                                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                           contrato_id BIGINT NOT NULL,
                                           status_contrato VARCHAR(20) NOT NULL,
                                           data_mudanca TIMESTAMP NOT NULL,
                                           CONSTRAINT fk_historico_contrato FOREIGN KEY (contrato_id) REFERENCES contrato(id)
);

CREATE TABLE pagamento (
                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           vinculo_id BIGINT NOT NULL,
                           contrato_id BIGINT,
                           pagamento_origem_id BIGINT,
                           tipo_receita VARCHAR(30) NOT NULL,
                           valor_pago NUMERIC(12, 2) NOT NULL,
                           forma_pagamento VARCHAR(30) NOT NULL,
                           status_pagamento VARCHAR(20) NOT NULL,
                           taxa_processamento NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
                           data_pagamento DATE NOT NULL,
                           CONSTRAINT fk_pagamento_vinculo FOREIGN KEY (vinculo_id) REFERENCES vinculo(id),
                           CONSTRAINT fk_pagamento_contrato FOREIGN KEY (contrato_id) REFERENCES contrato(id),
                           CONSTRAINT fk_pagamento_origem FOREIGN KEY (pagamento_origem_id) REFERENCES pagamento(id)
);

CREATE TABLE processo_juridico (
                                   id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                   vinculo_id BIGINT NOT NULL,
                                   area_direito VARCHAR(50) NOT NULL,
                                   tipo_processo VARCHAR(50) NOT NULL,
                                   grau_instancia VARCHAR(30),
                                   data_abertura DATE NOT NULL,
                                   valor_causa NUMERIC(15, 2) NOT NULL,
                                   duracao_estimada_dias INT NOT NULL,
                                   status_processo VARCHAR(30) NOT NULL,
                                   score_risco_perda NUMERIC(5, 4) NOT NULL,
                                   CONSTRAINT fk_processo_vinculo FOREIGN KEY (vinculo_id) REFERENCES vinculo(id)
);

CREATE TABLE movimentacao_processo (
                                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                       processo_id BIGINT NOT NULL,
                                       descricao VARCHAR(255) NOT NULL,
                                       data_movimentacao TIMESTAMP NOT NULL,
                                       CONSTRAINT fk_movimentacao_processo FOREIGN KEY (processo_id) REFERENCES processo_juridico(id)
);

CREATE TABLE acordo (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        processo_id BIGINT NOT NULL UNIQUE,
                        valor_acordo NUMERIC(15, 2) NOT NULL,
                        data_acordo DATE NOT NULL,
                        CONSTRAINT fk_acordo_processo FOREIGN KEY (processo_id) REFERENCES processo_juridico(id)
);

CREATE TABLE documento (
                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           vinculo_id BIGINT NOT NULL,
                           tipo_documento VARCHAR(50) NOT NULL,
                           area_direito VARCHAR(50) NOT NULL,
                           quantidade_paginas INT NOT NULL,
                           tempo_analise_seg NUMERIC(10, 2) NOT NULL,
                           indice_conformidade NUMERIC(5, 4) NOT NULL,
                           score_risco_clausula NUMERIC(5, 4) NOT NULL,
                           CONSTRAINT fk_documento_vinculo FOREIGN KEY (vinculo_id) REFERENCES vinculo(id)
);

CREATE TABLE evento_documento (
                                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                  documento_id BIGINT NOT NULL,
                                  status_documento VARCHAR(30) NOT NULL,
                                  revisao_humana BOOLEAN NOT NULL DEFAULT FALSE,
                                  data_evento TIMESTAMP NOT NULL,
                                  CONSTRAINT fk_evento_documento FOREIGN KEY (documento_id) REFERENCES documento(id)
);

CREATE TABLE execucao_automacao (
                                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                    vinculo_id BIGINT NOT NULL,
                                    tipo_automacao VARCHAR(50) NOT NULL,
                                    mes_competencia VARCHAR(7) NOT NULL,
                                    tarefas_processadas INT NOT NULL,
                                    taxa_sucesso_percentual NUMERIC(5, 2) NOT NULL,
                                    tempo_medio_processamento_min NUMERIC(8, 2) NOT NULL,
                                    horas_economizadas NUMERIC(10, 2) NOT NULL,
                                    score_erro_modelo NUMERIC(5, 4) NOT NULL,
                                    CONSTRAINT fk_automacao_vinculo FOREIGN KEY (vinculo_id) REFERENCES vinculo(id),
                                    CONSTRAINT uk_automacao_chave UNIQUE (vinculo_id, tipo_automacao, mes_competencia)
);

CREATE TABLE atendimento (
                             id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             vinculo_id BIGINT NOT NULL,
                             canal_atendimento VARCHAR(30) NOT NULL,
                             tempo_atendimento_min NUMERIC(8, 2) NOT NULL,
                             resolucao_primeiro_contato BOOLEAN NOT NULL,
                             data_atendimento TIMESTAMP NOT NULL,
                             CONSTRAINT fk_atendimento_vinculo FOREIGN KEY (vinculo_id) REFERENCES vinculo(id)
);

CREATE TABLE pesquisa_nps (
                              id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              atendimento_id BIGINT NOT NULL UNIQUE,
                              nota INT NOT NULL CHECK (nota BETWEEN 0 AND 10),
                              CONSTRAINT fk_nps_atendimento FOREIGN KEY (atendimento_id) REFERENCES atendimento(id)
);

CREATE TABLE fechamento_financeiro (
                                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                       legaltech_id BIGINT NOT NULL,
                                       mes_competencia VARCHAR(7) NOT NULL,
                                       custo_operacional NUMERIC(15, 2) NOT NULL,
                                       cac NUMERIC(12, 2) NOT NULL,
                                       ltv NUMERIC(12, 2) NOT NULL,
                                       CONSTRAINT fk_fechamento_legaltech FOREIGN KEY (legaltech_id) REFERENCES legaltech(id),
                                       CONSTRAINT uk_fechamento_competencia UNIQUE (legaltech_id, mes_competencia)
);

CREATE TABLE modelo_preditivo (
                                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                  alvo_preditivo VARCHAR(50) NOT NULL,
                                  versao VARCHAR(20) NOT NULL,
                                  ativo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE score_preditivo (
                                 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                 modelo_id BIGINT NOT NULL,
                                 vinculo_id BIGINT NOT NULL,
                                 valor_score NUMERIC(5, 4) NOT NULL,
                                 data_score TIMESTAMP NOT NULL,
                                 CONSTRAINT fk_score_modelo FOREIGN KEY (modelo_id) REFERENCES modelo_preditivo(id),
                                 CONSTRAINT fk_score_vinculo FOREIGN KEY (vinculo_id) REFERENCES vinculo(id)
);